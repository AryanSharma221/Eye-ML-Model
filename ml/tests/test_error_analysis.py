"""
Unit and Integration Tests for Medical Error Analysis Module.

Validates the contracts, data structures, and artifacts generated by ml.error_analysis:
1. per_image_predictions.csv structure and mathematical consistency
2. error_analysis.json schema and numerical bounds
3. confusion_matrix.png visualization generation
4. Grad-CAM error cases visual explainability artifacts
"""

import csv
import json
import os
import sys
import unittest
from PIL import Image

_PROJECT_ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
if _PROJECT_ROOT not in sys.path:
    sys.path.insert(0, _PROJECT_ROOT)

from ml.dataset_loader import CLASS_NAMES, NUM_CLASSES
from ml.error_analysis import render_annotated_confusion_matrix


class TestErrorAnalysisArtifacts(unittest.TestCase):
    """Test suite for validating generated error analysis artifacts."""

    @classmethod
    def setUpClass(cls):
        cls.eval_dir = os.path.join(_PROJECT_ROOT, "ml", "evaluation_results")
        cls.csv_path = os.path.join(cls.eval_dir, "per_image_predictions.csv")
        cls.json_path = os.path.join(cls.eval_dir, "error_analysis.json")
        cls.cm_png_path = os.path.join(cls.eval_dir, "confusion_matrix.png")
        cls.md_path = os.path.join(cls.eval_dir, "ERROR_ANALYSIS.md")
        cls.error_cases_dir = os.path.join(cls.eval_dir, "error_cases")

    def test_per_image_predictions_csv_exists_and_complete(self):
        """Verify per_image_predictions.csv exists, has 894 samples + header, and valid schema."""
        self.assertTrue(os.path.exists(self.csv_path), f"CSV not found at {self.csv_path}")

        expected_columns = {
            "sample_name",
            "relative_path",
            "true_label",
            "predicted_label",
            "confidence",
            "margin",
            "prob_cataract",
            "prob_diabetic_retinopathy",
            "prob_glaucoma",
            "prob_normal",
            "quality_gate_passed",
            "quality_gate_reason",
            "blur_score",
            "brightness_mean",
            "contrast_std",
            "inference_error",
        }

        with open(self.csv_path, "r", encoding="utf-8") as f:
            reader = csv.DictReader(f)
            headers = set(reader.fieldnames or [])
            self.assertTrue(expected_columns.issubset(headers), f"Missing columns: {expected_columns - headers}")

            rows = list(reader)
            self.assertEqual(len(rows), 894, f"Expected exactly 894 rows, got {len(rows)}")

            error_count = 0
            for idx, r in enumerate(rows):
                # Verify labels
                self.assertIn(r["true_label"], CLASS_NAMES)
                self.assertIn(r["predicted_label"], CLASS_NAMES)

                # Verify probabilities
                probs = [
                    float(r["prob_cataract"]),
                    float(r["prob_diabetic_retinopathy"]),
                    float(r["prob_glaucoma"]),
                    float(r["prob_normal"]),
                ]
                self.assertTrue(all(0.0 <= p <= 1.0 for p in probs))
                self.assertAlmostEqual(sum(probs), 1.0, places=2)

                conf = float(r["confidence"])
                max_prob = max(probs)
                self.assertAlmostEqual(conf, max_prob, places=3)

                is_err = r["inference_error"].lower() == "true"
                if r["true_label"] != r["predicted_label"]:
                    self.assertTrue(is_err, f"Row {idx}: true != pred but inference_error is False")
                    error_count += 1
                else:
                    self.assertFalse(is_err, f"Row {idx}: true == pred but inference_error is True")

            self.assertEqual(error_count, 109, f"Expected 109 misclassifications, got {error_count}")

    def test_error_analysis_json_schema_and_metrics(self):
        """Verify error_analysis.json contains complete summary and consistent math."""
        self.assertTrue(os.path.exists(self.json_path), f"JSON not found at {self.json_path}")

        with open(self.json_path, "r", encoding="utf-8") as f:
            data = json.load(f)

        # Check top-level keys
        for key in [
            "metadata",
            "summary",
            "per_class_performance",
            "confusion_matrix",
            "confidence_stratification",
            "quality_gate_audit",
            "root_cause_categories",
            "representative_gradcam_cases",
        ]:
            self.assertIn(key, data)

        s = data["summary"]
        self.assertEqual(s["total_test_images"], 894)
        self.assertEqual(s["correct_predictions"], 785)
        self.assertEqual(s["misclassified_predictions"], 109)
        self.assertAlmostEqual(s["overall_accuracy"], 785 / 894, places=4)
        self.assertAlmostEqual(s["overall_error_rate"], 109 / 894, places=4)

        # Check confusion matrix
        cm = data["confusion_matrix"]["matrix"]
        self.assertEqual(len(cm), 4)
        self.assertEqual(len(cm[0]), 4)
        row_sums = [sum(row) for row in cm]
        self.assertEqual(row_sums, [210, 233, 203, 248])
        self.assertEqual(sum(row_sums), 894)

        # Check high-confidence errors
        cs = data["confidence_stratification"]
        self.assertEqual(cs["high_confidence_errors_ge_80"]["count"], 24)
        self.assertEqual(cs["extreme_confidence_errors_ge_90"]["count"], 10)

    def test_confusion_matrix_rendering(self):
        """Verify confusion matrix image rendering works and outputs valid image."""
        test_out = os.path.join(self.eval_dir, "test_render_cm.png")
        try:
            sample_cm = [[180, 2, 15, 13], [8, 214, 2, 9], [8, 4, 176, 15], [4, 0, 29, 215]]
            render_annotated_confusion_matrix(sample_cm, CLASS_NAMES, test_out, 0.8781, 0.8778)
            self.assertTrue(os.path.exists(test_out))
            with Image.open(test_out) as im:
                self.assertEqual(im.size, (820, 800))
        finally:
            if os.path.exists(test_out):
                os.remove(test_out)

    def test_gradcam_error_cases_generated(self):
        """Verify Grad-CAM heatmaps are generated for representative error cases."""
        self.assertTrue(os.path.exists(self.error_cases_dir))
        files = [f for f in os.listdir(self.error_cases_dir) if f.endswith(".png")]
        self.assertGreaterEqual(len(files), 10, f"Expected at least 10 Grad-CAM cases, found {len(files)}")

        for fname in files:
            fpath = os.path.join(self.error_cases_dir, fname)
            self.assertGreater(os.path.getsize(fpath), 1000, f"Image {fname} too small")
            with Image.open(fpath) as im:
                self.assertGreater(im.width, 0)
                self.assertGreater(im.height, 0)

    def test_markdown_report_exists_and_has_clinical_notice(self):
        """Verify ERROR_ANALYSIS.md exists and contains prototype notice and section headers."""
        self.assertTrue(os.path.exists(self.md_path))
        with open(self.md_path, "r", encoding="utf-8") as f:
            content = f.read()

        self.assertIn("CLINICAL RESEARCH PROTOTYPE NOTICE", content)
        self.assertIn("Overall Test Accuracy:", content)
        self.assertIn("87.81%", content)
        self.assertIn("Dominant Confusion Pairs Analysis", content)
        self.assertIn("glaucoma", content.lower())
        self.assertIn("normal", content.lower())
        self.assertIn("Extreme-Confidence Failure Audit", content)


if __name__ == "__main__":
    unittest.main()
